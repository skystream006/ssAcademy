_LEVELS = ("SPROUT", "TRAIL", "SUMMIT")
_SLOTS = ("a", "b", "c", "d", "e", "f")
_GENERATED_COUNT = 997
_INFERENCE_PROMPTS = (
    "Which conclusion does the reason for that action support?",
    "What can a careful reader infer from the reason for that step?",
    "Which claim does the reason for that action support?",
    "What does the reasoning behind that decision suggest?",
    "Which inference fits the reason given for that step?",
    "What conclusion is justified by the evidence for that action?",
)


def _lower_first(text: str) -> str:
    return text[0].lower() + text[1:]


def _sentences(family: Family, values: dict[str, str], level: str) -> list[str]:
    sentences = []
    for step in family.steps:
        action = step.text.format_map(values)
        reason = step.reason.format_map(values)
        if level == "SPROUT":
            sentences.append(f"{action}.")
        elif level == "TRAIL":
            sentences.append(f"{action}, because {reason}.")
        else:
            contrast = step.contrast.format_map(values)
            sentences.append(f"Although {contrast}, {_lower_first(action)}, because {reason}.")
    return sentences


def _question(family: Family, case: int, focus: int, level: str) -> dict:
    values = dict(zip(_SLOTS, family.cases[case]))
    step = family.steps[focus]
    action = step.text.format_map(values)
    # Keep alternatives on the same reading target, not on another true fact.
    alternatives = [
        step.text.format_map(dict(zip(_SLOTS, family.cases[(case + offset) % len(family.cases)])))
        for offset in (1, 3)
    ]
    if level == "SPROUT":
        prompt = step.prompt.format_map(values)
        correct = f"{action}."
        distractors = [f"{alternative}." for alternative in alternatives]
    elif level == "TRAIL":
        prompt = f"{step.prompt.format_map(values)} {step.why.format_map(values)}"
        reason = step.reason.format_map(values)
        contrast = step.contrast.format_map(values)
        correct = f"{action}, because {reason}."
        distractors = [
            f"{alternative}, because {reason}." for alternative in alternatives
        ]
        distractors.append(f"{action}, because {contrast}, rather than because {reason}.")
    else:
        prompt = f"{step.prompt.format_map(values)} {_INFERENCE_PROMPTS[focus]}"
        conclusion = _lower_first(step.conclusion.format_map(values))
        correct = f"{action}. This supports the conclusion that {conclusion}"
        distractors = [
            f"{alternative}. This supports the conclusion that {conclusion}"
            for alternative in alternatives
        ]
        distractors.append(f"{action}. This gives no support for the conclusion that {conclusion}")
    return question(prompt, correct, distractors)


def _projects(level: str) -> Iterator[tuple[Family, int, int]]:
    if level not in _LEVELS:
        raise ValueError(f"Unknown reading level: {level}")
    # Interleave families so truncation does not omit a subject or a reading target.
    for case in range(7):
        for focus in range(6):
            for family in _FAMILIES:
                yield family, case, focus


def _selected_steps(focus: int, level: str) -> list[int]:
    """Six distinct event subsets per project, each retaining its question's fact."""
    if level == "SPROUT":
        return sorted((focus, (focus + 1) % 6, (focus + 3) % 6))
    if level == "TRAIL":
        return sorted((focus + offset) % 6 for offset in range(4))
    return [index for index in range(6) if index != (focus + 3) % 6]


def sequence(level: str) -> Iterator[dict]:
    """Yield 997 new sequencing activities; the caller adds identity metadata."""
    for family, case, focus in islice(_projects(level), _GENERATED_COUNT):
        values = dict(zip(_SLOTS, family.cases[case]))
        sentences = _sentences(family, values, level)
        selected = _selected_steps(focus, level)
        ordered = []
        for position, index in enumerate(selected):
            sentence = sentences[index]
            if position:
                previous = family.steps[selected[position - 1]].cue.format_map(values)
                if level == "SPROUT":
                    sentence = f"After {previous}, {_lower_first(sentence)}"
                elif level == "TRAIL":
                    sentence = f"After {previous}, {_lower_first(sentence)}"
                else:
                    # Put the temporal link outside the concessive clause.
                    sentence = (
                        f"After {previous}, "
                        f"{_lower_first(family.steps[index].text.format_map(values))}, "
                        f"because {family.steps[index].reason.format_map(values)} "
                        f"even though {family.steps[index].contrast.format_map(values)}."
                    )
            ordered.append(sentence)
        tiles, valid_orders = scramble_tiles(ordered)
        illustrations = {
            text: picture(family.event_symbols[index], text)
            for index, text in zip(selected, ordered)
        }
        yield {
            "title": family.title,
            "picture": picture(family.symbol, family.title),
            "tiles": tiles,
            "validOrders": valid_orders,
            "eventPictures": [illustrations[text] for text in tiles],
            "question": _question(family, case, focus, level),
            "hint": (
                "Find the event with no earlier-event clue. Each 'after' clue links "
                "an event to the one that must already have happened. Then reread "
                "the detail asked about."
            ),
        }


def detective(level: str) -> Iterator[dict]:
    """Yield 997 new single-evidence activities; the caller adds metadata."""
    for family, case, focus in islice(_projects(level), _GENERATED_COUNT):
        values = dict(zip(_SLOTS, family.cases[case]))
        yield {
            "title": family.title,
            "picture": picture(family.symbol, family.title),
            "passage": _sentences(family, values, level),
            "question": _question(family, case, focus, level),
            "evidence": focus,
            "hint": (
                "Find the one sentence about the detail in the question. "
                "Use what that sentence says, not a fact about a different task."
                if level == "SPROUT" else
                "Match the question to one specific action and its reason. "
                "The evidence sentence must support the whole answer; a true "
                "statement about a different action is not evidence for this question."
            ),
        }
