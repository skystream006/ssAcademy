"""Authored, reproducible sequencing and evidence-reading catalogues.

Each of the 24 families has seven concrete projects and six independent reading
targets.  A project is not a name substitution: its materials, decisions, tools,
observations and destination change together.  Detective revisits a project
through six different questions.  Sequence uses six different event selections,
with an explicit predecessor clue on every event except the first.

Keep the six facts independent: a Detective answer must not be restated by a
different fact.  Reasons and conclusions belong to their own fact, not to a
later sentence explaining it.  The catalogue order is part of the pack format.
"""

from dataclasses import dataclass
from itertools import islice
from typing import Iterator

from .common import picture, question, scramble_tiles


@dataclass(frozen=True)
class Step:
    text: str
    cue: str
    prompt: str
    reason: str
    why: str
    contrast: str
    conclusion: str


@dataclass(frozen=True)
class Family:
    title: str
    symbol: str
    steps: tuple[Step, ...]
    cases: tuple[tuple[str, ...], ...]
    event_symbols: tuple[str, ...]


def _family(title: str, symbol: str, steps: tuple[Step, ...],
            cases: tuple[str, ...], event_symbols: tuple[str, ...]) -> Family:
    rows = tuple(tuple(row.split("|")) for row in cases)
    if len(steps) != 6 or len(rows) != 7 or len(event_symbols) != 6:
        raise ValueError(f"{title}: expected six reading targets and seven projects")
    if any(len(row) != 6 or len(set(row)) != 6 for row in rows):
        raise ValueError(f"{title}: each project needs six distinct answer details")
    if any(len({row[column] for row in rows}) != 7 for column in range(6)):
        raise ValueError(f"{title}: alternatives for each reading target must be distinct")
    for slot, step in zip(("a", "b", "c", "d", "e", "f"), steps):
        if "{" + slot + "}" not in step.text:
            raise ValueError(f"{title}: the action must include its own answer detail")
    return Family(title, symbol, steps, rows, event_symbols)


