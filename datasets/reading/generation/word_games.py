def _situations(level: str) -> Iterator[tuple[_Family, str, _Frame]]:
    if level not in ("SPROUT", "TRAIL", "SUMMIT"):
        raise ValueError(f"Unknown reading level: {level}")
    if len(_FAMILIES) != 20:
        raise ValueError("The word-game source requires twenty semantic families")
    for family in _FAMILIES:
        frames = getattr(family, level.lower())
        if len(family.items) != 10 or len(set(family.items)) != 10 or len(frames) != 5:
            raise ValueError(f"Incomplete word-game family: {family.title}")
    emitted = 0
    for frame_index in range(5):
        for item_index in range(10):
            for family in _FAMILIES:
                if emitted == 997:
                    return
                frame = getattr(family, level.lower())[frame_index]
                yield family, family.items[item_index], frame
                emitted += 1


def missing(level: str) -> Iterator[dict]:
    """Yield exactly 997 clued, single-gap activities for a supported level."""
    for family, item, frame in _situations(level):
        passage = " ".join(part.format(item=item, answer="___") for part in frame.parts)
        yield {
            "title": f"{family.title}: {item}",
            "picture": picture(family.symbol, f"{family.title}; the sentence is about the {item}."),
            "passage": [passage],
            "question": question("Which word or phrase belongs in the gap?", frame.answer, frame.distractors),
            "hint": f"Use the meaning of the whole sentence. {frame.prompt}",
        }


def scramble(level: str) -> Iterator[dict]:
    """Yield exactly 997 phrase-tile activities with text-supported bonuses."""
    for family, item, frame in _situations(level):
        ordered = [part.format(item=item, answer=frame.answer) for part in frame.parts]
        if len(set(ordered)) != len(ordered):
            raise ValueError(f"Repeated phrase tile in {family.title}: {item}")
        tiles, orders = scramble_tiles(ordered)
        yield {
            "title": f"{family.title}: {item}",
            "picture": picture(family.symbol, f"{family.title}; arrange a sentence about the {item}."),
            "tiles": tiles,
            "validOrders": orders,
            "question": question(f"Bonus: {frame.prompt}", frame.answer, frame.distractors),
            "hint": (
                "Start with the capital letter and finish with the full stop. "
                "Keep each phrase together and reread to check who does what."
                if level == "SPROUT" else
                "Start with the capitalized phrase and finish with the full stop. "
                "Use the comma and connecting words to join the reason, action, or contrast."
            ),
        }
