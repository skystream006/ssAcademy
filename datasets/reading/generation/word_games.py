"""Reproducible vocabulary and sentence-ordering activities.

Each domain has ten compatible concrete subjects and five different situations
at each reading level. The 20 domains therefore provide 1,000 distinct sentences
per level; the public generators supply the first 997, leaving room for the
three retained activities. Frames are interleaved across domains so truncation
does not remove a domain or a language objective.

The same situation supports two different reading tasks: completing a precisely
clued word, and arranging phrase tiles before answering a vocabulary question.
Pipes mark authored phrase boundaries, not arbitrary word splits. Capitalization,
punctuation, and attached complements constrain the intended sentence order.
Four-tile frames separate the subject from its predicate in the middle tiles;
movable adverbials stay attached to that predicate rather than forming a tile.
"""

from dataclasses import dataclass
from typing import Iterator

from .common import picture, question, scramble_tiles


@dataclass(frozen=True)
class _Frame:
    parts: tuple[str, ...]
    answer: str
    distractors: tuple[str, ...]
    prompt: str


def _f(text: str, answer: str, distractors: str, prompt: str) -> _Frame:
    parts = tuple(text.split("|"))
    wrong = tuple(distractors.split("|"))
    if text.count("{answer}") != 1 or not 3 <= len(parts) <= 7:
        raise ValueError("A frame needs one answer and three to seven phrase tiles")
    if not 2 <= len(wrong) <= 3 or len(set((answer, *wrong))) != len(wrong) + 1:
        raise ValueError("A frame needs distinct, unambiguous vocabulary choices")
    return _Frame(parts, answer, wrong, prompt)


