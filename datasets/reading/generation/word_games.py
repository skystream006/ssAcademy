def _situations(level: str) -> Iterator[tuple[_Family, str, _Frame]]:
    if level not in ("SPROUT", "TRAIL", "SUMMIT"):
        raise ValueError(f"Unknown reading level: {level}")
    if len(_FAMILIES) != 20:
        raise ValueError("The word-game source requires twenty semantic families")
    for family in _FAMILIES:
        frames = getattr(family, level.lower())
        if len(family.items) != 10 or len(set(family.items)) != 10 or len(frames) != 5:
            raise ValueError(f"Incomplete word-game family: {family.title}")
    emitted = 0
    for frame_index in range(5):
        for item_index in range(10):
            for family in _FAMILIES:
                if emitted == 997:
                    return
                frame = getattr(family, level.lower())[frame_index]
                yield family, family.items[item_index], frame
                emitted += 1


@dataclass(frozen=True)
class _Selection:
    description: str
    variants: tuple[tuple[str, str], ...]


def _s(
    description: str,
    sprout: tuple[str, str],
    trail: tuple[str, str],
    summit: tuple[str, str],
) -> _Selection:
    """Pair observable evidence with level-specific choices and selection rules."""
    variants = (sprout, trail, summit)
    for index, (choices, reason) in enumerate(variants):
        words = choices.split("|")
        if len(words) != (3 if index == 0 else 4) or len(set(words)) != len(words):
            raise ValueError("Selection scenes need distinct, level-appropriate choices")
        if not reason or not description:
            raise ValueError("A selection needs both a reason and observable evidence")
    return _Selection(description, variants)


